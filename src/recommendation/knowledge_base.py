def get_recommendation(disease_class):
    return RECOMMENDATIONS.get(disease_class, DEFAULT_RECOMMENDATION)

def format_recommendation(rec):
    output = []
    output.append(f"DISEASE: {rec['disease_name']}")
    output.append(f"PATHOGEN: {rec['pathogen']}")
    output.append(f"DESCRIPTION: {rec['description']}")
    output.append("")
    
    if rec['pesticides']:
        output.append("PESTICIDE RECOMMENDATIONS:")
        for i, p in enumerate(rec['pesticides'], 1):
            output.append(f"  {i}. {p['name']} ({p['type']})")
            output.append(f"     Application: {p['application']}")
            output.append(f"     Timing: {p['timing']}")
            output.append(f"     Notes: {p['notes']}")
            output.append("")
    else:
        output.append("PESTICIDE RECOMMENDATIONS: No specific pesticide treatment (healthy or viral disease)")
        output.append("")
    
    output.append("CULTURAL PRACTICES:")
    for i, cp in enumerate(rec['cultural_practices'], 1):
        output.append(f"  {i}. {cp}")
    output.append("")
    
    output.append("PREVENTIVE MEASURES:")
    for i, pm in enumerate(rec['preventive_measures'], 1):
        output.append(f"  {i}. {pm}")
    output.append("")
    
    output.append("IMPORTANT: Follow the product label and local agricultural authority guidance for dosage, application rates, pre-harvest intervals (PHI), and safety precautions. Pesticide registrations vary by region and crop.")
    
    return "\n".join(output)

